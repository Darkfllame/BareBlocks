fn RegistryFieldsFormatter(comptime T: type) type {
    return struct {
        const Self = @This();

        const PreSufName = struct {
            prefix: []const u8 = &.{},
            suffix: []const u8 = &.{},
        };

        reg: *const IdentifierList(T),
        mode: union(enum) {
            @"switch",
            @"enum": struct {
                self_name: utils.Identifier,
                ps: PreSufName = .{},
                no_trail_limit: usize = 4,
                exaustive: bool = false,
                write_max: bool = true,
                default: ?u32 = null,
            },
        },
        entry_mode: union(enum) {
            number,
            id: PreSufName,
            name: PreSufName,
            pascal_name: PreSufName,
        },
        write_quotes: bool = false,

        pub fn format(self: *const Self, writer: *Io.Writer) Io.Writer.Error!void {
            const max = self.reg.map.count();
            const should_trail = switch (self.mode) {
                .@"switch" => true,
                .@"enum" => |e| max <= e.no_trail_limit or e.default != null or e.write_max,
            };
            var it = self.reg.iterator();
            var count: usize = 0;
            var max_idn: u32 = 0;
            while (it.next()) |entry| : (count += 1) {
                const id, const idn, _ = entry;

                max_idn = @max(max_idn, idn);

                switch (self.mode) {
                    .@"enum" => try writer.print("@{qf} =", .{id.alt(.omit_minecraft)}),
                    .@"switch" => try writer.print(".@{qf} =>", .{id.alt(.omit_minecraft)}),
                }
                if (self.write_quotes) try writer.writeByte('"');
                switch (self.entry_mode) {
                    .number => try writer.printInt(idn, 10, .lower, .{}),
                    .name, .id => |ps| try writer.print("{s}{f}{s}", .{
                        ps.prefix,
                        id.alt(switch (self.entry_mode) {
                            .id => .full,
                            .name => .omit_minecraft,
                            else => unreachable,
                        }),
                        ps.suffix,
                    }),
                    .pascal_name => |ps| {
                        try writer.writeAll(ps.prefix);
                        if (!id.isVanilla()) {
                            try pascalizeInto(id.namespace(), writer);
                        }
                        try pascalizeInto(id.path(), writer);
                        try writer.writeAll(ps.suffix);
                    },
                }
                if (self.write_quotes) try writer.writeByte('"');

                if ((count < (max - 1)) or should_trail) {
                    try writer.writeByte(',');
                }
            }

            if (self.mode == .@"enum") {
                const e = self.mode.@"enum";
                if (!e.exaustive) {
                    try writer.writeByte('_');
                    if (((count < max) and (max > 0)) or should_trail) try writer.writeByte(',');
                }
                if (e.default) |value| {
                    try writer.print("pub const default: @\"{s}{f}{f}{s}\" = @fromBackingInt({d});", .{
                        e.ps.prefix,
                        PascalFormatter.from(if (!e.self_name.isVanilla()) e.self_name.namespace() else ""),
                        PascalFormatter.from(e.self_name.path()),
                        e.ps.suffix,
                        value,
                    });
                }
                if (e.write_max) {
                    try writer.print("pub const max_value: @\"{s}{f}{f}{s}\" = @fromBackingInt({d});", .{
                        e.ps.prefix,
                        PascalFormatter.from(if (!e.self_name.isVanilla()) e.self_name.namespace() else ""),
                        PascalFormatter.from(e.self_name.path()),
                        e.ps.suffix,
                        max_idn,
                    });
                }

                if (e.self_name.eql(.vanilla("builtin_registry"))) {
                    try writer.writeAll("pub const self_type: BuiltinRegistry = .root;");
                } else 
                try writer.print("pub const self_type: BuiltinRegistry = .@\"{f}\";", .{
                    e.self_name.alt(.omit_minecraft),
                });
            }
        }
    };
}

fn printAstErrors(ast: std.zig.Ast, writer: *Io.Writer) Io.Writer.Error!void {
    for (ast.errors) |err| {
        try std.zig.Ast.renderError(ast, err, writer);
        try writer.writeByte('\n');
    }
}

fn pascalizeInto(str: []const u8, writer: *Io.Writer) Io.Writer.Error!void {
    var next_upper: bool = true;
    for (str) |c| {
        try writer.writeByte(sw: switch (c) {
            '0'...'9' => {
                next_upper = true;
                break :sw c;
            },
            'a'...'z', 'A'...'Z' => if (next_upper) {
                next_upper = false;
                break :sw c & (~@as(u8, 32));
            } else c,
            else => {
                next_upper = true;
                continue;
            },
        });
    }
}

fn pascalize(str: []const u8, alloc: Allocator) Allocator.Error![]u8 {
    const res = try alloc.alloc(u8, str.len);
    errdefer alloc.free(res);

    var w = Io.Writer.fixed(res);
    pascalizeInto(str, &w) catch unreachable;

    return alloc.realloc(res, w.end);
}

/// `synced` is the second output of build/DumpVanilla.java
fn printRegistriesFile(
    reg_file: *const RegistriesReport,
    dpr: *const DatapackReport,
    synced: []const u8,
    io: Io,
    data_dir: Io.Dir,
    arena: Allocator,
    out: *Io.Writer,
) !void {
    try out.writeAll(gen_file_header ++
        \\const root = @This();
        \\const std = @import("std");
        \\
        \\pub const RegistryProperties = struct { dynamic: bool, stable: bool, has_tags: bool };
        \\pub const properties = std.StaticStringMap(RegistryProperties).initComptime(.{
        \\    .{ "minecraft:root", RegistryType.getProperties(.root) },
        \\
    );

    var dp_reg_it = dpr.registries.iterator();
    while (dp_reg_it.next()) |entry| {
        try out.print("    .{{ RegistryType.getIdentifier(.@\"{0f}\"), RegistryType.getProperties(.@\"{0f}\") }},\n", .{
            entry.key_ptr.alt(.omit_minecraft),
        });
    }

    try out.writeAll(
        \\
        \\});
        \\pub const RegistryType = enum {
        \\    root,
        \\
    );
    dp_reg_it = dpr.registries.iterator();
    while (dp_reg_it.next()) |entry| {
        try out.print("    @\"{f}\",\n", .{entry.key_ptr.alt(.omit_minecraft)});
    }
    try out.writeAll(
        \\pub fn getProperties(self: RegistryType) RegistryProperties {
        \\    return switch (self) {
        \\        .root => .{ .dynamic = false, .stable = false, .has_tags = false },
        \\
    );
    dp_reg_it = dpr.registries.iterator();
    while (dp_reg_it.next()) |entry| {
        try out.print("        .@\"{f}\" => .{{ .dynamic = {}, .stable = {}, .has_tags = {} }},\n", .{
            entry.key_ptr.alt(.omit_minecraft),
            entry.value_ptr.dynamic,
            entry.value_ptr.stable,
            entry.value_ptr.has_tags,
        });
    }
    try out.writeAll(
        \\    };
        \\}
        \\
        \\pub fn getIdentifier(self: RegistryType) []const u8 {
        \\    return switch(self) {
        \\        .root => "minecraft:root",
        \\
    );
    dp_reg_it = dpr.registries.iterator();
    while (dp_reg_it.next()) |entry| {
        try out.print("        .@\"{f}\" => \"{f}\",\n", .{
            entry.key_ptr.alt(.omit_minecraft), entry.key_ptr.alt(.full),
        });
    }
    try out.writeAll(
        \\    };
        \\}
        \\};
        \\
    );

    try out.print(
        \\pub const BuiltinRegistry = enum(u32) {{
        \\    root = std.math.maxInt(u32),
        \\    {f}
        \\    
        \\    pub fn RealType(comptime self: BuiltinRegistry) type {{
        \\        return switch(self) {{
        \\            .root => BuiltinRegistry,
        \\            {f}
        \\        }};
        \\    }}
        \\
        \\    pub fn identifier(self: BuiltinRegistry) []const u8 {{
        \\        return switch(self) {{
        \\            .root => "minecraft:root",
        \\            {f}
        \\        }};
        \\    }}
        \\}};
        \\
    , .{
        RegistryFieldsFormatter(RegistriesReport.Registry){
            .reg = &reg_file.entries,
            .mode = .{ .@"enum" = .{
                .self_name = .vanilla("builtin_registry"),
                .no_trail_limit = std.math.maxInt(usize),
                .exaustive = true,
            } },
            .entry_mode = .number,
        },
        RegistryFieldsFormatter(RegistriesReport.Registry){
            .reg = &reg_file.entries,
            .mode = .@"switch",
            .entry_mode = .{ .pascal_name = .{ .suffix = "Registry" } },
        },
        RegistryFieldsFormatter(RegistriesReport.Registry){
            .reg = &reg_file.entries,
            .mode = .@"switch",
            .entry_mode = .{ .id = .{} },
            .write_quotes = true,
        },
    });

    var count: usize = 0;
    var regs_it = reg_file.entries.iterator();
    while (regs_it.next()) |entry| : (count += 1) {
        const id, _, const reg = entry;

        try out.print(
            \\pub const @"{f}{f}Registry" = enum(u32) {{
            \\    {f}
            \\
            \\    pub const properties: RegistryProperties = root.properties.get(self_type.identifier()).?;
            \\}};
            \\
        , .{
            PascalFormatter.from(if (!id.isVanilla()) id.namespace() else ""),
            PascalFormatter.from(id.path()),
            RegistryFieldsFormatter(void){
                .reg = &reg.entries,
                .mode = .{ .@"enum" = .{
                    .self_name = id,
                    .ps = .{ .suffix = "Registry" },
                    .no_trail_limit = std.math.maxInt(usize),
                    .default = reg.default,
                } },
                .entry_mode = .number,
            },
        });
    }

    try out.writeAll(
        \\pub const SynchronizedRegistry = struct { id: []const u8, entries: []const []const u8 };
        \\
        \\
    );
    // Parse the dump first, the synchronized registries' entries are also needed for the tags
    const Synced = struct { id: []const u8, entries: []const []const u8 };
    var synced_list = std.ArrayList(Synced).empty;
    var known_pack: ?[3][]const u8 = null;
    {
        var lines = std.mem.tokenizeScalar(u8, synced, '\n');
        while (lines.next()) |raw_line| {
            const line = std.mem.trimEnd(u8, raw_line, "\r");
            var words = std.mem.splitScalar(u8, line, ' ');
            const kind = words.next().?;
            if (std.mem.eql(u8, kind, "known_pack")) {
                known_pack = .{
                    words.next() orelse return error.UnexpectedToken,
                    words.next() orelse return error.UnexpectedToken,
                    words.next() orelse return error.UnexpectedToken,
                };
            } else if (std.mem.eql(u8, kind, "registry")) {
                const id = words.next() orelse return error.UnexpectedToken;
                var entries = std.ArrayList([]const u8).empty;
                var it = std.mem.tokenizeScalar(u8, words.rest(), ',');
                while (it.next()) |entry| try entries.append(arena, entry);
                try synced_list.append(arena, .{ .id = id, .entries = entries.items });
            } else return error.UnexpectedToken;
        }
    }
    const pack = known_pack orelse return error.MissingField;
    if (synced_list.items.len == 0) return error.MissingField;

    try out.print(
        \\/// Registry entries from this pack are sent without their data, the vanilla client already has it.
        \\pub const known_pack = .{{ .namespace = "{s}", .id = "{s}", .version = "{s}" }};
        \\
        \\/// Registries sent during configuration, both them and their entries in the same order as vanilla.
        \\pub const synchronized = [_]SynchronizedRegistry{{
        \\
    , .{ pack[0], pack[1], pack[2] });
    for (synced_list.items) |registry| {
        try out.print("    .{{ .id = \"{s}\", .entries = &.{{", .{registry.id});
        for (registry.entries, 0..) |entry, i| try out.print("{s}\"{s}\"", .{ if (i == 0) " " else ", ", entry });
        try out.writeAll(" } },\n");
    }
    try out.writeAll("};\n\n");

    // Tags are sent for the static (built-in) and synchronized registries, see vanilla's
    // `TagNetworkSerialization.serializeTagsToNetwork`. Static registries use their protocol ids,
    // synchronized ones the order they're sent in.
    const TagRegistry = struct { id: []const u8, ids: std.StringHashMapUnmanaged(u32) };
    var tag_registries = std.ArrayList(TagRegistry).empty;
    {
        var reg_it = reg_file.entries.iterator();
        while (reg_it.next()) |entry| {
            const reg_id, _, const reg = entry;
            var ids = std.StringHashMapUnmanaged(u32).empty;
            var entry_it = reg.entries.iterator();
            while (entry_it.next()) |e| {
                const e_id, const num, _ = e;
                try ids.put(arena, try std.fmt.allocPrint(arena, "{f}", .{e_id.alt(.full)}), num);
            }
            try tag_registries.append(arena, .{ .id = try std.fmt.allocPrint(arena, "{f}", .{reg_id.alt(.full)}), .ids = ids });
        }
        for (synced_list.items) |registry| {
            var ids = std.StringHashMapUnmanaged(u32).empty;
            for (registry.entries, 0..) |e, i| try ids.put(arena, e, @intCast(i));
            try tag_registries.append(arena, .{ .id = registry.id, .ids = ids });
        }
    }
    std.mem.sortUnstable(TagRegistry, tag_registries.items, {}, struct {
        fn lessThan(_: void, a: TagRegistry, b: TagRegistry) bool {
            return std.mem.lessThan(u8, a.id, b.id);
        }
    }.lessThan);

    try out.writeAll(
        \\pub const Tag = struct { name: []const u8, entries: []const u32 };
        \\pub const RegistryTags = struct { registry: []const u8, tags: []const Tag };
        \\
        \\/// Every tag of the static and synchronized registries, resolved to numeric ids like vanilla's `update_tags`.
        \\pub const tags = [_]RegistryTags{
        \\
    );
    for (tag_registries.items) |registry| {
        const colon = std.mem.indexOfScalar(u8, registry.id, ':').?;
        const tags_path = try std.fmt.allocPrint(arena, "data/{s}/tags/{s}", .{ registry.id[0..colon], registry.id[colon + 1 ..] });
        var resolver: TagResolver = .{ .arena = arena, .ids = &registry.ids };
        if (!try resolver.loadDir(io, data_dir, tags_path, registry.id[0..colon])) continue;

        const names = try arena.dupe([]const u8, resolver.sources.keys());
        std.mem.sortUnstable([]const u8, names, {}, stringLessThan);

        try out.print("    .{{ .registry = \"{s}\", .tags = &.{{\n", .{registry.id});
        for (names) |name| {
            // Like vanilla, tags with missing required entries are skipped
            const entries = try resolver.resolve(name) orelse continue;
            try out.print("        .{{ .name = \"{s}\", .entries = &.{{", .{name});
            // No trailing comma so rendering keeps them on one line
            for (entries, 0..) |e, i| try out.print("{s}{d}", .{ if (i == 0) " " else ", ", e });
            try out.writeAll(if (entries.len == 0) "} },\n" else " } },\n");
        }
        try out.writeAll("    } },\n");
    }
    try out.writeAll("};\n");
}

/// Same rules as vanilla's `TagLoader`: entries keep their first-seen order without duplicates (`LinkedHashSet`),
/// `#tag` entries add the referenced tag's entries, missing optional entries are skipped and a missing required
/// one makes the whole tag missing.
const TagResolver = struct {
    const Value = struct { id: []const u8, tag: bool, required: bool };

    arena: Allocator,
    ids: *const std.StringHashMapUnmanaged(u32),
    sources: std.StringArrayHashMapUnmanaged([]const Value) = .empty,
    /// `null` when missing.
    resolved: std.StringHashMapUnmanaged(?[]const u32) = .empty,
    visiting: std.StringHashMapUnmanaged(void) = .empty,

    /// Returns whether the registry has any tag.
    fn loadDir(self: *TagResolver, io: Io, data_dir: Io.Dir, path: []const u8, namespace: []const u8) !bool {
        var dir = data_dir.openDir(io, path, .{ .iterate = true }) catch |e| switch (e) {
            error.FileNotFound => return false,
            else => |err| return err,
        };
        defer dir.close(io);

        var walker = try dir.walk(self.arena);
        defer walker.deinit();
        while (try walker.next(io)) |entry| {
            if (entry.kind != .file or !std.mem.endsWith(u8, entry.basename, ".json")) continue;
            const name = try std.fmt.allocPrint(self.arena, "{s}:{s}", .{ namespace, entry.path[0 .. entry.path.len - ".json".len] });
            const content = try dir.readFileAlloc(io, entry.path, self.arena, .unlimited);
            try self.sources.put(self.arena, name, try self.parse(content));
        }
        return self.sources.count() != 0;
    }

    fn parse(self: *TagResolver, content: []const u8) ![]const Value {
        var input: Io.Reader = .fixed(content);
        var json_r: serial.JsonReader = undefined;
        json_r.init(self.arena, &input);
        defer json_r.deinit();

        const root = try serial.Value.deserialize(&json_r.mapr);
        if (root != .aggregate) return error.UnexpectedToken;
        const values = root.aggregate.get("values") orelse return &.{};
        if (values != .array) return error.UnexpectedToken;

        const out = try self.arena.alloc(Value, values.array.len);
        for (out, 0..) |*v, i| {
            const raw, const required = switch (values.array.get(i)) {
                .string => |str| .{ str, true },
                .aggregate => |agg| .{
                    switch (agg.get("id") orelse return error.MissingField) {
                        .string => |str| str,
                        else => return error.UnexpectedToken,
                    },
                    if (agg.get("required")) |r| (r.asBool() orelse return error.UnexpectedToken) else true,
                },
                else => return error.UnexpectedToken,
            };
            const tag = std.mem.startsWith(u8, raw, "#");
            const id = if (tag) raw[1..] else raw;
            v.* = .{
                .id = if (std.mem.indexOfScalar(u8, id, ':') == null)
                    try std.fmt.allocPrint(self.arena, "minecraft:{s}", .{id})
                else
                    try self.arena.dupe(u8, id),
                .tag = tag,
                .required = required,
            };
        }
        return out;
    }

    fn resolve(self: *TagResolver, name: []const u8) !?[]const u32 {
        if (self.resolved.get(name)) |r| return r;
        const values = self.sources.get(name) orelse return null;
        if (self.visiting.contains(name)) {
            std.debug.print("tag cycle through {s}\n", .{name});
            return error.TagCycle;
        }
        try self.visiting.put(self.arena, name, {});
        defer _ = self.visiting.remove(name);

        var set = std.AutoArrayHashMapUnmanaged(u32, void).empty;
        var missing = false;
        for (values) |v| {
            if (v.tag) {
                if (try self.resolve(v.id)) |sub| {
                    for (sub) |e| try set.put(self.arena, e, {});
                } else if (v.required) missing = true;
            } else if (self.ids.get(v.id)) |num| {
                try set.put(self.arena, num, {});
            } else if (v.required) missing = true;
        }

        const result: ?[]const u32 = if (missing) null else set.keys();
        if (missing) std.debug.print("tag {s} has missing required entries, skipped like vanilla does\n", .{name});
        try self.resolved.put(self.arena, name, result);
        return result;
    }
};

fn printPacketsFile(pack_file: *const PacketsReport, out: *Io.Writer) !void {
    const pack_file_mut = @constCast(pack_file);
    try out.writeAll(gen_file_header ++
        \\pub fn registry(comptime PacketRegistry: type, comptime source: type) PacketRegistry {
        \\    return .{.entries = .init(.{
    );

    var side_it = pack_file_mut.ids.iterator();
    while (side_it.next()) |entry| {
        const side = entry.key;
        try out.print(".{t} = .init(.{{", .{side});

        var phase_it = entry.value.iterator();
        while (phase_it.next()) |entry2| {
            const phase = entry2.key;
            try out.print(".{t} = &.{{", .{phase});

            var last_id: u32 = 0;
            var packet_it = entry2.value.iterator();
            while (packet_it.next()) |entry3| {
                const id, const idn, _ = entry3;
                if (idn - last_id > 1) {
                    for (last_id..idn - 1) |_| {
                        try out.writeAll(".{.write_cushion=0, .resource=\"none\",.callback=null},");
                    }
                }

                try out.print(
                    \\.{{
                    \\  .write_cushion=512,
                    \\  .resource="{f}",
                    \\  .callback= if (@hasDecl(source, "{t}bound/{t}/{0f}")) source.@"{1t}bound/{2t}/{0f}" else null,
                    \\}},
                , .{
                    id.alt(.omit_minecraft),
                    side,
                    phase,
                });

                last_id = idn;
            }

            try out.writeAll("},");
        }

        try out.writeAll("}),");
    }

    try out.writeAll(
        \\    })};
        \\}
    );
}

/// Value index of a state's property, in vanilla order.
fn stateValueIndex(prop: *const BlocksReport.Property, state: *const BlocksReport.State, name: []const u8) !usize {
    const value = state.properties.get(name) orelse return error.MissingField;
    return switch (prop.data) {
        // Vanilla's order is always "true", "false"
        .bool => @intFromBool(!value.bool),
        .integer => |ints| @intCast(value.integer - ints[0]),
        .enumeration => |names| names.getIndex(value.enumeration).?,
    };
}

fn valueCount(prop: *const BlocksReport.Property) usize {
    return switch (prop.data) {
        .bool => 2,
        .integer => |ints| ints.len,
        .enumeration => |names| names.count(),
    };
}

fn propertyLessThan(_: void, a: *const BlocksReport.Property, b: *const BlocksReport.Property) bool {
    switch (std.mem.order(u8, a.name, b.name)) {
        .lt => return true,
        .gt => return false,
        .eq => {},
    }
    const a_count = valueCount(a);
    const b_count = valueCount(b);
    if (a_count != b_count) return a_count < b_count;
    return switch (a.data) {
        .bool => false,
        .integer => |ints| ints[0] < b.data.integer[0],
        .enumeration => |names| for (names.keys(), b.data.enumeration.keys()) |ak, bk| {
            switch (std.mem.order(u8, ak, bk)) {
                .lt => break true,
                .gt => break false,
                .eq => {},
            }
        } else false,
    };
}

fn stringLessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// `property_names` is the output of build/DumpProperties.java: `<FIELD_NAME> <name> <value>,<value>,...` lines
fn printBlockStatesFile(report: *const BlocksReport, property_names: []const u8, arena: Allocator, out: *Io.Writer) !void {
    const SortedEntry = struct {
        id: utils.Identifier,
        entry: *const BlocksReport.Entry,
        first_state: u32,

        fn lessThan(_: void, a: @This(), b: @This()) bool {
            return a.first_state < b.first_state;
        }
    };
    const Layout = struct { property: usize, bit_offset: usize, bit_size: usize, stride: usize };

    if (report.states_data.len > std.math.maxInt(u32) + 1) return error.Overflow;

    // Properties, sorted so the output doesn't depend on the hash map order
    const props = try arena.alloc(*const BlocksReport.Property, report.all_properties.count());
    {
        var it = report.all_properties.keyIterator();
        var i: usize = 0;
        while (it.next()) |key| : (i += 1) props[i] = key.*;
    }
    std.mem.sortUnstable(*const BlocksReport.Property, props, {}, propertyLessThan);
    if (props.len > std.math.maxInt(u8) + 1) return error.Overflow;

    var prop_indices = std.AutoHashMapUnmanaged(*const BlocksReport.Property, usize).empty;
    for (props, 0..) |prop, i| try prop_indices.put(arena, prop, i);

    // Mojang's names, names alone collide so properties are matched by "<name> <values>"
    var field_names = std.StringHashMapUnmanaged([]const u8).empty;
    {
        var lines = std.mem.tokenizeScalar(u8, property_names, '\n');
        while (lines.next()) |line| {
            const space = std.mem.indexOfScalar(u8, line, ' ') orelse return error.UnexpectedToken;
            const gop = try field_names.getOrPut(arena, std.mem.trimEnd(u8, line[space + 1 ..], "\r"));
            if (gop.found_existing) return error.DuplicateField;
            gop.value_ptr.* = try std.ascii.allocLowerString(arena, line[0..space]);
        }
    }
    const prop_ids = try arena.alloc([]const u8, props.len);
    for (props, prop_ids) |prop, *id| {
        var key = Io.Writer.Allocating.init(arena);
        try key.writer.print("{s} ", .{prop.name});
        switch (prop.data) {
            .bool => try key.writer.writeAll("true,false"),
            .integer => |ints| for (ints, 0..) |v, i| try key.writer.print("{s}{d}", .{ if (i == 0) "" else ",", v }),
            .enumeration => |names| for (names.keys(), 0..) |v, i| try key.writer.print("{s}{s}", .{ if (i == 0) "" else ",", v }),
        }
        id.* = field_names.get(key.written()) orelse {
            std.debug.print("no BlockStateProperties field for property: {s}\n", .{key.written()});
            return error.MissingField;
        };
    }

    // Blocks, sorted by their first state
    const entries = try arena.alloc(SortedEntry, report.entries.count());
    {
        var it = report.entries.iterator();
        var i: usize = 0;
        while (it.next()) |kv| : (i += 1) {
            var first: u32 = std.math.maxInt(u32);
            var last: u32 = 0;
            for (kv.value_ptr.states) |state| {
                first = @min(first, state.id);
                last = @max(last, state.id);
            }
            // A block's states are contiguous
            if (last - first + 1 != kv.value_ptr.states.len) return error.LengthMismatch;
            entries[i] = .{ .id = kv.key_ptr.*, .entry = kv.value_ptr, .first_state = first };
        }
    }
    std.mem.sortUnstable(SortedEntry, entries, {}, SortedEntry.lessThan);
    // `state_blocks` is a u16 table
    if (entries.len > std.math.maxInt(u16) + 1) return error.Overflow;

    const state_bits = try arena.alloc(u16, report.states_data.len);
    const state_blocks = try arena.alloc(u16, report.states_data.len);

    // The types and the API are in src/block_states.zig, this is just the data
    try out.writeAll(gen_file_header ++
        \\/// Mojang's names for the properties (BlockStateProperties' fields), same order as `Data().properties`.
        \\pub const PropertyId = enum(u8) {
        \\
    );
    for (prop_ids) |id| try out.print("    {f},\n", .{std.zig.fmtId(id)});
    try out.writeAll(
        \\};
        \\
        \\pub fn Data(comptime Property: type, comptime Block: type) type {
        \\    return struct {
        \\        pub const properties = [_]Property{
        \\
    );
    for (props) |prop| {
        try out.print("            .{{ .name = \"{s}\", .kind = .{s}, .values = &.{{ ", .{ prop.name, switch (prop.data) {
            .bool => "boolean",
            .integer => "integer",
            .enumeration => "enumeration",
        } });
        switch (prop.data) {
            .bool => try out.writeAll("\"true\", \"false\""),
            .integer => |ints| for (ints, 0..) |v, i| try out.print("{s}\"{d}\"", .{ if (i == 0) "" else ", ", v }),
            .enumeration => |names| for (names.keys(), 0..) |v, i| try out.print("{s}\"{s}\"", .{ if (i == 0) "" else ", ", v }),
        }
        try out.writeAll(" } },\n");
    }
    try out.writeAll(
        \\        };
        \\
        \\        pub const blocks = [_]Block{
        \\
    );
    for (entries, 0..) |se, block_index| {
        const entry = se.entry;

        // Same order as the state ids
        const names = try arena.alloc([]const u8, entry.properties.count());
        {
            var it = entry.properties.keyIterator();
            var i: usize = 0;
            while (it.next()) |key| : (i += 1) names[i] = key.*;
        }
        std.mem.sort([]const u8, names, {}, stringLessThan);

        const layouts = try arena.alloc(Layout, names.len);
        var bit_offset: usize = 0;
        for (names, layouts) |name, *layout| {
            const prop = entry.properties.get(name).?;
            const bit_size = std.math.log2_int_ceil(usize, @max(valueCount(prop), 2));
            layout.* = .{
                .property = prop_indices.get(prop).?,
                .bit_offset = bit_offset,
                .bit_size = bit_size,
                .stride = undefined,
            };
            bit_offset += bit_size;
        }
        if (bit_offset > 16) return error.Overflow;
        {
            var stride: usize = 1;
            var i = names.len;
            while (i > 0) {
                i -= 1;
                layouts[i].stride = stride;
                stride *= valueCount(entry.properties.get(names[i]).?);
            }
            if (stride != entry.states.len) return error.LengthMismatch;
        }

        var default_state: ?u32 = null;
        for (entry.states) |state| {
            var bits: u16 = 0;
            var id: usize = se.first_state;
            for (names, layouts) |name, layout| {
                const value_index = try stateValueIndex(entry.properties.get(name).?, state, name);
                bits |= @intCast(value_index << @intCast(layout.bit_offset));
                id += value_index * layout.stride;
            }
            // The whole point, the math must give back vanilla's ids
            if (id != state.id) return error.UnexpectedToken;
            state_bits[state.id] = bits;
            state_blocks[state.id] = @intCast(block_index);
            if (state.default) {
                if (default_state != null) return error.DuplicateField;
                default_state = state.id;
            }
        }

        try out.print("            .{{ .name = \"{s}:{s}\", .first_state = {d}, .state_count = {d}, .default_state = {d}, .properties = &.{{", .{
            se.id.namespace(),
            se.id.path(),
            se.first_state,
            entry.states.len,
            default_state orelse return error.MissingField,
        });
        for (layouts, 0..) |layout, i| {
            try out.print("{s}.{{ .property = .{f}, .bit_offset = {d}, .bit_size = {d}, .stride = {d} }}", .{
                if (i == 0) " " else ", ", std.zig.fmtId(prop_ids[layout.property]), layout.bit_offset, layout.bit_size, layout.stride,
            });
        }
        try out.writeAll(if (layouts.len == 0) "} },\n" else " } },\n");
    }
    try out.writeAll(
        \\        };
        \\    };
        \\}
        \\
        \\pub const state_bits = [_]u16{
    );
    for (state_bits, 0..) |bits, i| try out.print("{s}{d},", .{ if (i % 32 == 0) "\n    " else "", bits });
    try out.writeAll("\n};\n\n");

    try out.writeAll("pub const state_blocks = [_]u16{");
    for (state_blocks, 0..) |index, i| try out.print("{s}{d},", .{ if (i % 32 == 0) "\n    " else "", index });
    try out.writeAll("\n};\n");
}

pub fn IdentifierList(comptime T: type) type {
    return struct {
        const Self = @This();

        const SliceType = if (@sizeOf(T) == 0) void else [*]T;
        const entries_default = if (SliceType == void) {} else &[_]T{};

        map: std.HashMapUnmanaged(utils.Identifier, u32, utils.Identifier.HashCtx, std.hash_map.default_max_load_percentage) = .empty,
        entries: SliceType = entries_default,
        mask: std.DynamicBitSetUnmanaged = .{},
        capacity: u32 = 0,

        pub const Iterator = struct {
            list: *const Self,
            mask_it: std.DynamicBitSetUnmanaged.Iterator(.{}),

            pub fn next(self: *Iterator) ?struct { utils.Identifier, u32, T } {
                const idx: u32 = @intCast(self.mask_it.next() orelse return null);
                var map_it = self.list.map.iterator();
                while (map_it.next()) |en| {
                    if (en.value_ptr.* != idx) continue;
                    return .{ en.key_ptr.*, idx, if (SliceType == void) {} else self.list.entries[idx] };
                }
                unreachable; // should not happen
            }
        };

        pub fn deinit(self: *Self, allocator: Allocator) void {
            self.map.deinit(allocator);
            allocator.free(self.entries);
            self.mask.deinit(allocator);
        }

        pub fn ensureTotalCapacity(self: *Self, allocator: Allocator, capacity: u32) Allocator.Error!void {
            try self.map.ensureTotalCapacity(allocator, capacity);
            if (self.capacity < capacity) {
                try self.mask.resize(allocator, capacity, false);
                if (SliceType != void) {
                    const better_capacity = std.ArrayList(u32).growCapacity(capacity);
                    self.entries = (try allocator.realloc(self.entries[0..self.capacity], better_capacity)).ptr;
                }
                self.capacity = capacity;
            }
        }

        pub fn set(self: *Self, allocator: Allocator, id: utils.Identifier, idn: u32, v: T) !void {
            try self.ensureTotalCapacity(allocator, idn + 1);

            if (self.mask.isSet(idn)) return error.DuplicateField;

            const gop = try self.map.getOrPut(allocator, id);
            if (gop.found_existing) return error.DuplicateField;
            errdefer self.map.removeByPtr(gop.key_ptr);

            gop.value_ptr.* = idn;
            self.mask.set(idn);
            if (SliceType != void) self.entries[idn] = v;
        }

        pub fn clearRetainingCapacity(self: *Self) void {
            self.map.clearRetainingCapacity();
            self.mask.unsetAll();
        }

        pub fn iterator(self: *const Self) Iterator {
            return .{ .list = self, .mask_it = self.mask.iterator(.{}) };
        }
    };
}

pub const PascalFormatter = struct {
    value: []const u8,

    pub fn from(value: []const u8) PascalFormatter {
        return .{ .value = value };
    }

    pub fn format(self: PascalFormatter, writer: *Io.Writer) Io.Writer.Error!void {
        return pascalizeInto(self.value, writer);
    }
};

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();

    var args_it = try init.minimal.args.iterateAllocator(arena);
    defer args_it.deinit();
    _ = args_it.skip(); // Skip self path

    const dirpath = args_it.next() orelse return error.BadArgument;
    const which_str = args_it.next() orelse return error.BadArgument;
    const out_filepath = args_it.next() orelse return error.BadArgument;

    const which = std.meta.stringToEnum(ReportKind, which_str) orelse return error.BadArgument;

    const dir = try Io.Dir.cwd().openDir(init.io, dirpath, .{});
    defer dir.close(init.io);

    var out_file = try Io.Dir.cwd().createFile(init.io, out_filepath, .{ .lock = .exclusive });
    defer out_file.close(init.io);

    var buf: [256]u8 = undefined;
    var fw = out_file.writer(init.io, &buf);

    var aw = Io.Writer.Allocating.init(init.gpa);
    defer aw.deinit();

    {
        const report_file = try dir.openFile(init.io, which.filename(), .{ .lock = .shared });
        defer report_file.close(init.io);

        var fr = report_file.reader(init.io, &buf);

        var json_r: serial.JsonReader = undefined;
        json_r.init(init.gpa, &fr.interface);
        defer json_r.deinit();

        switch (which) {
            .registries => {
                const reg_file = try json_r.mapr.deserialize(RegistriesReport);
                const dpr = blk: {
                    var buf2: [buf.len]u8 = undefined;
                    const datapack_file = try dir.openFile(init.io, "reports/datapack.json", .{ .lock = .shared });
                    defer datapack_file.close(init.io);

                    var fr2 = datapack_file.reader(init.io, &buf2);

                    var json_r2: serial.JsonReader = undefined;
                    json_r2.initWithArena(&json_r.mapr.arena, &fr2.interface);
                    defer {
                        json_r2.redeemArena(&json_r.mapr.arena);
                        json_r2.deinit();
                    }

                    break :blk try json_r2.mapr.deserialize(DatapackReport);
                };

                const synced_path = args_it.next() orelse return error.BadArgument;
                const synced = try Io.Dir.cwd().readFileAlloc(init.io, synced_path, arena, .unlimited);

                printRegistriesFile(&reg_file, &dpr, synced, init.io, dir, arena, &aw.writer) catch |e| return switch (e) {
                    error.WriteFailed => error.OutOfMemory,
                    else => |err| err,
                };
            },
            .packets => {
                const pack_file = try json_r.mapr.deserialize(PacketsReport);

                printPacketsFile(&pack_file, &aw.writer) catch |e| return switch (e) {
                    error.WriteFailed => error.OutOfMemory,
                    // else => |err| err,
                };
            },
            .blocks => {
                const blocks_file = try json_r.mapr.deserialize(BlocksReport);
                const names_path = args_it.next() orelse return error.BadArgument;
                const property_names = try Io.Dir.cwd().readFileAlloc(init.io, names_path, arena, .unlimited);

                printBlockStatesFile(&blocks_file, property_names, arena, &aw.writer) catch |e| return switch (e) {
                    error.WriteFailed => error.OutOfMemory,
                    else => |err| err,
                };
            },
        }
    }

    aw.writer.writeByte(0) catch return error.OutOfMemory;

    const written = aw.written();

    var ast = try std.zig.Ast.parse(init.gpa, written[0 .. written.len - 1 :0], .{ .mode = .zig });
    defer ast.deinit(init.gpa);

    if (ast.errors.len != 0) {
        const stderr = std.debug.lockStderr(&buf);
        defer std.debug.unlockStderr();

        const w = &stderr.file_writer.interface;

        printAstErrors(ast, w) catch {};
        w.flush() catch {};
        fw.interface.print("attempted writing file:\n{s}\n", .{written}) catch {};
        fw.flush() catch {};
        return error.AstError;
    }

    ast.render(init.gpa, &fw.interface, .{}) catch |e| return switch (e) {
        error.WriteFailed => fw.err.?,
        else => |err| err,
    };

    try fw.flush();
}
