pub fn main(init: std.process.Init) !void {
    var r = std.Io.Reader.fixed(&bytes);
    const res = try net.packets.encryption_request_s2c.readRoot(.fullInput(init.gpa, init.arena), &r);
    std.log.info("packet: {f}", .{net.packets.encryption_request_s2c.formatted(res)});

    var p = res.public_key.ptr;
    const pkey = crypto.d2i_PUBKEY(null, @ptrCast(&p), @intCast(res.public_key.len)).?;
    defer crypto.EVP_PKEY_free(pkey);

    const bio_out = crypto.BIO_new(crypto.BIO_s_mem().?).?;
    defer _ = crypto.BIO_free(bio_out);

    _ = crypto.EVP_PKEY_print_public(bio_out, pkey, 0, null);
    _ = crypto.BIO_puts(bio_out, ", ");
    _ = crypto.EVP_PKEY_print_private(bio_out, pkey, 0, null);

    var data: [*]u8 = undefined;
    _ = crypto.BIO_get_mem_data(bio_out, &data);
    const len = crypto.BIO_get_buffer_num_lines(bio_out);

    const bio_out_res = std.mem.sliceTo(data, 0);
    std.log.info("result: {d}/{d} \"{s}\"", .{ len, bio_out_res.len, bio_out_res });
}
